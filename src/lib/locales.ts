/* -------------------------------------------------------------------------- */
/*  لغات الواجهة                                                               */
/*                                                                             */
/*  العربية والإنجليزية كاملتان؛ وبقية اللغات تغطّي رحلة المشجّع — التنقّل         */
/*  والواجهة والتذاكر والمناطق والبلاغ والتتبّع والمباراة. ما لم يُترجَم بعد يسقط  */
/*  إلى الإنجليزية لا إلى فراغ، فإضافة لغة جديدة لا تكسر شيئاً ولا تنتظر اكتمالها. */
/*                                                                             */
/*  كونسول العمليات يبقى بالعربية والإنجليزية: مستخدموه فريق واحد معروف، لا     */
/*  جمهور قادم من ثمانين بلداً.                                                  */
/* -------------------------------------------------------------------------- */

export type Dict = Partial<Record<StringKey, string>>;

export interface LocaleInfo {
  code: Locale;
  /** الاسم كما يكتبه أهله — لا «الإسبانية» في قائمة يقرؤها إسباني */
  native: string;
  dir: "rtl" | "ltr";
}

export const LOCALES: LocaleInfo[] = [
  { code: "ar", native: "العربية", dir: "rtl" },
  { code: "en", native: "English", dir: "ltr" },
  { code: "es", native: "Español", dir: "ltr" },
  { code: "fr", native: "Français", dir: "ltr" },
  { code: "pt", native: "Português", dir: "ltr" },
  { code: "de", native: "Deutsch", dir: "ltr" },
  { code: "it", native: "Italiano", dir: "ltr" },
  { code: "tr", native: "Türkçe", dir: "ltr" },
  { code: "ja", native: "日本語", dir: "ltr" },
  { code: "ko", native: "한국어", dir: "ltr" },
  { code: "zh", native: "中文", dir: "ltr" },
  { code: "ur", native: "اردو", dir: "rtl" },
  { code: "fa", native: "فارسی", dir: "rtl" },
];

const BY_CODE = new Map(LOCALES.map((l) => [l.code, l]));

export const isLocale = (value: string): value is Locale => BY_CODE.has(value as Locale);

export const localeInfo = (code: Locale): LocaleInfo => BY_CODE.get(code) ?? LOCALES[0];

export const localeDir = (code: Locale): "rtl" | "ltr" => localeInfo(code).dir;

/**
 * لغة المحتوى.
 *
 * أسماء الملاعب والمباريات والمناطق مخزّنة بلغتين فقط. من يقرأ بالعربية يأخذ
 * العربية، وكل من سواه يأخذ الإنجليزية — لا تُعرض العربية لقارئ ياباني لمجرّد
 * أن اليابانية ليست إنجليزية.
 */
export const contentLocale = (code: Locale): "ar" | "en" => (code === "ar" ? "ar" : "en");

